/**
 * @module package-game
 * @description Builds a standalone 3D game in a new output directory; optional unsigned Windows unpacked executable, never the editor installer.
 */
const fs = require("fs"), path = require("path"), { build } = require("esbuild");

async function packageGame(project, destination, desktop = false) {
    const root = path.resolve(__dirname, ".."), output = path.resolve(destination);
    // No deletion or reuse: an existing path (including a link) fails before any build writes.
    fs.mkdirSync(output);
    const stage = path.join(output, "app"); fs.mkdirSync(stage);
    const collector = path.join(output, "collector.cjs");
    await build({ entryPoints: [path.join(root, "src/electron/GamePackageExport.ts")], bundle: true,
        platform: "node", format: "cjs", target: "node22", outfile: collector });
    const { collectGamePackage, game3DHtml } = require(collector);
    const file = fs.realpathSync.native(project);
    if (fs.statSync(file).size > 20_000_000) throw new Error("Entry project exceeds 20MB.");
    const serialized = await collectGamePackage(file, fs.readFileSync(file, "utf8"));
    const player = await build({ entryPoints: [path.join(root, "src/player3d/index.ts")], bundle: true,
        platform: "browser", format: "iife", target: "es2020", minify: true, write: false });
    fs.writeFileSync(path.join(stage, "game.html"), game3DHtml(serialized, Buffer.from(player.outputFiles[0].contents)), { flag: "wx" });
    fs.writeFileSync(path.join(output, "game.cfgame.json"), serialized, { flag: "wx" });
    await build({ entryPoints: [path.join(root, "src/player3d/desktopMain.js")], bundle: true,
        platform: "node", format: "cjs", target: "node22", external: ["electron"], outfile: path.join(stage, "main.cjs") });
    await build({ entryPoints: [path.join(root, "src/player3d/progressPreload.js")], bundle: true,
        platform: "node", format: "cjs", target: "node22", external: ["electron"], outfile: path.join(stage, "progressPreload.js") });
    fs.writeFileSync(path.join(stage, "package.json"), JSON.stringify({ name: "canvas-fogworks-game", version: "0.0.1",
        private: true, description: "Standalone Canvas Fogworks 3D game", main: "main.cjs" }, null, 2), { flag: "wx" });
    // This file was generated by this invocation at an exclusively created path.
    fs.unlinkSync(collector);
    if (desktop) {
        if (process.platform !== "win32") throw new Error("Executable packaging currently supports Windows only.");
        const { build: pack, Platform } = require("electron-builder");
        await pack({ projectDir: stage, targets: Platform.WINDOWS.createTarget("dir"), publish: "never",
            config: { extends: null, appId: "com.canvasfogworks.game", productName: "Canvas Fogworks Game",
                electronVersion: require("electron/package.json").version, asar: true, npmRebuild: false,
                directories: { output: path.join(output, "desktop") }, files: ["main.cjs", "progressPreload.js", "game.html", "package.json"],
                win: { signAndEditExecutable: false }, forceCodeSigning: false } });
    }
    console.log(`Game output: ${output}`);
    return output;
}
if (require.main === module) {
    const [project, destination, flag] = process.argv.slice(2);
    if (!project || !destination || (flag && flag !== "--desktop") || process.argv.length > 5) {
        console.error('Usage: npm run package:game -- "entry.vde" "NEW output directory" [--desktop]'); process.exitCode = 1;
    } else packageGame(project, destination, flag === "--desktop").catch(error => { console.error(error); process.exitCode = 1; });
}
module.exports = { packageGame };
